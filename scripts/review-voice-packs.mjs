function openingTemplate(persona, aClause, bNoun, cPredicate) {
  switch (persona) {
    case "대학생":
      return `${aClause} ${bNoun} 마련이 ${cPredicate}`;
    case "직장인":
      return `${aClause} ${bNoun}까지 ${cPredicate}`;
    case "주부":
      return `${aClause} ${bNoun}부터 ${cPredicate}`;
    case "사업자":
      return `${aClause} ${bNoun} 쪽은 ${cPredicate}`;
    case "육아맘":
      return `${aClause} ${bNoun}만큼은 ${cPredicate}`;
    case "경단녀":
      return `${aClause} ${bNoun}도 ${cPredicate}`;
    default:
      throw new Error(`unknown persona ${persona}`);
  }
}

export function openingLine(persona, formal, a, b, c) {
  const predicate = formal ? toFormal(OPEN_C[persona][c]) : OPEN_C[persona][c];
  return openingTemplate(persona, OPEN_A[persona][a], OPEN_B[persona][b], predicate);
}

