function walkPackStrings(fn) {
  for (const group of [OPEN_A, OPEN_B, OPEN_C, CORE_A, SHORT_B, LONG_B, DOUBT, EXTRA, DIARY, MORE, PHOTO, ZERO, PERF]) {
    for (const list of Object.values(group)) fn(list);
  }
  for (const byRating of Object.values(CLOSER)) {
    for (const list of Object.values(byRating)) fn(list);
  }
}

export function assertVoicePacks() {
  const formalMisses = [];
  const lengths = [
    [OPEN_A, 25],
    [OPEN_B, 20],
    [OPEN_C, 20]
  ];
  for (const [group, size] of lengths) {
    for (const [persona, list] of Object.entries(group)) {
      if (list.length !== size) throw new Error(`${persona} opening list is ${list.length}, expected ${size}`);
      if (new Set(list).size !== list.length) throw new Error(`${persona} opening list has duplicates`);
    }
  }
  walkPackStrings(list => {
    for (const line of list) {
      if (FAMILY_RELAY_RE.test(line)) throw new Error(`family relay in pack: ${line}`);
      if (TIME_RE.test(line)) throw new Error(`time of day in pack: ${line}`);
      if (REGION_RE.test(line)) throw new Error(`region in pack: ${line}`);
      if (/\d/.test(line.replaceAll("0원", ""))) throw new Error(`stray digit in pack: ${line}`);
      if (/분경|요일|corpus-/i.test(line)) throw new Error(`forbidden token in pack: ${line}`);
      const formal = toFormal(line);
      if (/요[.!?]/.test(formal) || /요$/.test(formal) || /[🙂😅👍ㅠㅎㅋ]/.test(formal)) {
        formalMisses.push(formal);
      }
    }
  });
  if (formalMisses.length) {
    throw new Error(`formal endings left 요:\n${formalMisses.join("\n")}`);
  }
}

