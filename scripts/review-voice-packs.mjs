function openingTemplate(persona, aClause, bNoun, cPredicate, variant) {
  const topic = variant === 1 ? `${bNoun} 조건` : `${bNoun} 안내`;
  const particle = hasFinal(topic) ? "을" : "를";
  return `${aClause} ${topic}${particle} 보고 ${cPredicate}`;
}

export function openingLine(persona, formal, a, b, c) {
  const aClause = OPEN_A[persona][a];
  const bNoun = OPEN_B[persona][b];
  const predicate = formal ? toFormal(OPEN_C[persona][c]) : OPEN_C[persona][c];
  return openingTemplate(persona, aClause, bNoun, predicate, (a + b) % 2);
}

