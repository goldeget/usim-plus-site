/* ------------------------------------------------------------------ *
 * Pack integrity gate. Runs at import time; a bad string breaks the
 * build before any row is generated.
 * ------------------------------------------------------------------ */

const MONEY_SUFFIXES = ["수수료", "수리비", "재료비", "등록금", "비용", "회비", "경비", "대금", "요금", "수당", "식대", "이자", "자금", "값", "비", "료", "금", "돈"];
const CORE_WHITELIST = new Set(["생활", "살림", "카드", "장보"]);

function nounCore(noun) {
  let core = noun;
  for (;;) {
    const hit = MONEY_SUFFIXES.find(s => core.endsWith(s) && core.length - s.length >= 2);
    if (!hit) break;
    core = core.slice(0, -hit.length);
  }
  return core.length >= 2 ? core : noun;
}

const PERSONA_LABEL_RE = {
  대학생: /대학생/,
  직장인: /직장인/,
  주부: /주부/,
  사업자: /사업자(?!금)/,
  육아맘: /육아맘/,
  경단녀: /경단녀/
};

const SOLVED_RE = /이해|좋았|만족|아쉬|명확|괜찮|편했|편하/;
const RISK_RE = /대출|급전|보이스피싱|스미싱|내구제|대포폰|폰깡|선불폰|유심\s*개통|신용대출|당일\s*지급|카드론|기대출|사기/;
const FREE_RE = /무료|수수료|부담|무료|한 푼|비용/;

function checkLineBasics(line, where, problems) {
  const fail = msg => problems.push(`${msg} in ${where}: ${line}`);
  if (FAMILY_RELAY_RE.test(line)) fail("family relay");
  if (TIME_RE.test(line)) fail("time of day");
  if (REGION_RE.test(line)) fail("region");
  if (/\d/.test(line.replaceAll("0원", ""))) fail("stray digit");
  if (/분경|요일|corpus-/i.test(line)) fail("forbidden token");
  if (BANNED_PHRASE_RE.test(line)) fail("banned phrase");
  if (RISK_RE.test(line)) fail("risk phrase");
  if (BANTAL_RE.test(line)) fail("raw 반말/jamo");
  const formal = toFormal(line);
  if (BAD_FORMAL_RE.test(formal)) problems.push(`bad formal ending in ${where}: ${formal}`);
}

function checkPersonaLabels(persona, line, where, problems) {
  for (const [label, re] of Object.entries(PERSONA_LABEL_RE)) {
    if (label !== persona && re.test(line)) {
      problems.push(`foreign label ${label} in ${persona} ${where}: ${line}`);
    }
  }
}

export function assertVoicePacks() {
  const problems = [];
  for (const [group, size] of [[OPEN_A, 25], [OPEN_B, 20], [OPEN_C, 20]]) {
    for (const [persona, list] of Object.entries(group)) {
      if (list.length !== size) problems.push(`${persona} opening list is ${list.length}, expected ${size}`);
      if (new Set(list).size !== list.length) problems.push(`${persona} opening list has duplicates`);
    }
  }
  for (const persona of Object.keys(OPEN_A)) {
    for (const aClause of OPEN_A[persona]) {
      if (!PERSONA_MARKERS[persona].test(aClause)) {
        problems.push(`${persona} OPEN_A misses persona marker: ${aClause}`);
      }
    }
    for (const aClause of OPEN_A[persona]) {
      for (const bNoun of OPEN_B[persona]) {
        const core = nounCore(bNoun);
        if (!CORE_WHITELIST.has(core) && aClause.includes(core)) {
          problems.push(`${persona} OPEN_A/B noun repeat (${core}): ${aClause} × ${bNoun}`);
        }
        if (core !== bNoun && aClause.includes(bNoun)) {
          problems.push(`${persona} OPEN_A repeats full noun: ${aClause} × ${bNoun}`);
        }
      }
    }
  }
  const groups = [
    ["OPEN_A", OPEN_A], ["OPEN_B", OPEN_B], ["OPEN_C", OPEN_C], ["ANCHOR", ANCHOR],
    ["CORE_A", CORE_A], ["SHORT_B", SHORT_B], ["LONG_B", LONG_B], ["DOUBT", DOUBT],
    ["EXTRA", EXTRA], ["DIARY", DIARY], ["MORE", MORE], ["PHOTO", PHOTO],
    ["ZERO", ZERO], ["FREE", FREE], ["RELIEF", RELIEF]
  ];
  for (const [name, group] of groups) {
    for (const [persona, list] of Object.entries(group)) {
      for (const line of list) {
        checkLineBasics(line, `${name}/${persona}`, problems);
        checkPersonaLabels(persona, line, `${name}/${persona}`, problems);
      }
    }
  }
  for (const [persona, byRating] of Object.entries(CLOSER)) {
    for (const [rating, list] of Object.entries(byRating)) {
      for (const line of list) {
        checkLineBasics(line, `CLOSER/${persona}/${rating}`, problems);
        checkPersonaLabels(persona, line, `CLOSER/${persona}/${rating}`, problems);
        if (!SOLVED_RE.test(line)) problems.push(`closer misses relief marker: ${line}`);
      }
    }
  }
  for (const persona of Object.keys(ANCHOR)) {
    for (const line of ANCHOR[persona]) {
      if (!PERSONA_LABEL_RE[persona].test(line)) problems.push(`${persona} ANCHOR misses label: ${line}`);
    }
    for (const line of ANCHOR.대학생) if (!/용돈/.test(line)) problems.push(`대학생 ANCHOR misses 용돈: ${line}`);
    for (const line of ANCHOR.사업자) if (!/사업자금/.test(line)) problems.push(`사업자 ANCHOR misses 사업자금: ${line}`);
  }
  for (const persona of Object.keys(ZERO)) {
    for (const line of ZERO[persona]) {
      if (!line.includes("0원")) problems.push(`${persona} ZERO misses 0원: ${line}`);
    }
    for (const line of FREE[persona]) {
      if (!line.includes("0원")) problems.push(`${persona} FREE misses 0원: ${line}`);
      if (!FREE_RE.test(line)) problems.push(`${persona} FREE misses free marker: ${line}`);
    }
    for (const line of [...SHORT_B[persona], ...LONG_B[persona]]) {
      if (!/사진|캡처/.test(line)) problems.push(`${persona} core misses photo step: ${line}`);
      if (!/회사|그쪽|담당자/.test(line)) problems.push(`${persona} core misses company: ${line}`);
      if (!/절차|진행|처리/.test(line)) problems.push(`${persona} core misses procedure: ${line}`);
      if ((line.match(/캡처/g) || []).length > 1) problems.push(`${persona} core repeats 캡처: ${line}`);
    }
    for (const line of PHOTO[persona]) {
      if (/캡처/.test(line)) problems.push(`${persona} PHOTO must not use 캡처: ${line}`);
    }
  }
  if (problems.length) {
    throw new Error(`${problems.length} voice pack problem(s):\n${problems.slice(0, 60).join("\n")}`);
  }
}

assertVoicePacks();
