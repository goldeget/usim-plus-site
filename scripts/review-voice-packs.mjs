export function toFormal(text) {
  let value = String(text);
  for (const [from, to] of FORMAL_RULES) value = value.replaceAll(from, to);
  return value;
}

function assertFormal(text, label) {
  const formal = toFormal(text);
  if (/요[.!?]/.test(formal) || /요$/.test(formal)) {
    throw new Error(`formal ending left 요 in ${label}: ${formal}`);
  }
  if (/[🙂😅👍ㅠㅎㅋ]/.test(formal)) throw new Error(`formal emoticon in ${label}`);
  return formal;
}

