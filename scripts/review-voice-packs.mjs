function speak(text, formal) {
  return formal ? toFormal(text) : text;
}

function pick(list, index) {
  return list[((index % list.length) + list.length) % list.length];
}

const LONG_OPEN = ["문의를 남겼어요", "상담을 신청했어요", "연락을 드렸어요"];

export function anchorLine(persona, formal, index) {
  return speak(pick(ANCHOR[persona], index), formal);
}

export function reliefLine(persona, formal, index) {
  return speak(pick(RELIEF[persona], index), formal);
}

export function shortCore(persona, formal, when, chTo, a, b, withLead) {
  const lead = withLead ? `${CORE_A[persona][a % CORE_A[persona].length]} ` : "";
  const tail = speak(pick(SHORT_B[persona], b), formal);
  return `${when} ${lead}${chTo} 유심 혜택에 ${tail}`;
}

export function longCore(persona, formal, when, chTo, a, c) {
  const lead = CORE_A[persona][a % CORE_A[persona].length];
  const opened = speak(pick(LONG_OPEN, a + c), formal);
  return `${when} ${lead} ${chTo} 유심 혜택에 ${opened}. ${speak(pick(LONG_B[persona], c), formal)}`;
}

