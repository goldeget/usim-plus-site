export function toFormal(text) {
  let value = String(text);
  for (const [from, to] of FORMAL_RULES) value = value.replaceAll(from, to);
  return value;
}

/** Trailing consonant check for the 이/가 template slot. */
function hasFinal(word) {
  const code = String(word).charCodeAt(String(word).length - 1);
  return code >= 0xAC00 && code <= 0xD7A3 && (code - 0xAC00) % 28 !== 0;
}

function igA(word) {
  return hasFinal(word) ? "이" : "가";
}

